def validate_script_data(script_data):
    """校验剧本数据 schema，返回错误列表（空列表=通过）。
    
    校验项：
    - 顶层为 dict
    - shots/scenes 非空列表
    - 每个 shot 有 video_prompt 且非空
    - 每个 shot 有 dialogue 或 dialogues（可为空，但字段需存在）
    """
    errors = []
    if not isinstance(script_data, dict):
        return ["顶层应为 JSON 对象（dict），而非列表或其他类型"]
    
    scenes = script_data.get("shots") or script_data.get("scenes") or []
    if not isinstance(scenes, list) or len(scenes) == 0:
        errors.append("shots/scenes 应为非空列表")
        return errors
    
    missing_prompt = 0
    missing_dialogue_field = 0
    for i, shot in enumerate(scenes):
        if not isinstance(shot, dict):
            errors.append(f"shot[{i}] 应为 dict")
            continue
        if not (shot.get("video_prompt") or "").strip():
            missing_prompt += 1
        if "dialogue" not in shot and "dialogues" not in shot:
            missing_dialogue_field += 1
    
    if missing_prompt > 0:
        errors.append(f"{missing_prompt} 个 shot 缺少 video_prompt")
    if missing_dialogue_field > 0:
        errors.append(f"{missing_dialogue_field} 个 shot 缺少 dialogue/dialogues 字段")
    
    return errors


