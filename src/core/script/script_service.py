def parse_with_repair(client, full_prompt, max_retries=1, system_prompt=None):
    """解析 LLM 返回的 JSON，失败时把错误喂回 LLM 重试。
    
    Args:
        client: LLMClient 实例
        full_prompt: 原始 prompt
        max_retries: 修复重试次数（默认 1）
    
    Returns:
        解析后的 dict
    
    Raises:
        RuntimeError: 重试后仍无法解析
    """
    result = client.generate_script(full_prompt, system_prompt=system_prompt)
    if not result:
        detail = getattr(client, "last_error", "") or "未知原因"
        raise RuntimeError(f"剧本生成失败：LLM 返回为空。原因: {detail}")
    
    result = strip_markdown_fence(result)
    for attempt in range(max_retries + 1):
        try:
            data = json.loads(result.strip())
            # 校验 schema
            errors = validate_script_data(data)
            if not errors:
                return data
            # 校验失败，触发修复重试
            if attempt >= max_retries:
                raise RuntimeError(f"剧本 schema 校验失败: {'; '.join(errors)}")
        except json.JSONDecodeError as e:
            # 先本地抢救（截断/尾逗号），成功就不必再烧一次 LLM（5-10 分钟）
            salvaged = salvage_script_json(result)
            if salvaged is not None:
                errors = validate_script_data(salvaged)
                if not errors:
                    print(f"[剧本] JSON 解析失败（{e}），本地抢救成功："
                          f"{len(salvaged.get('shots') or salvaged.get('scenes') or [])} 个镜头")
                    return salvaged
            if attempt >= max_retries:
                preview = result[:200] if isinstance(result, str) else result
                raise RuntimeError(f"AI 返回的内容不是有效 JSON。错误: {e}；返回片段: {preview}")
        
        # 修复重试：把错误喂回 LLM（已终止就别再发一次请求）
        if _cancel_requested():
            raise RuntimeError("剧本生成失败：用户已终止")
        repair_prompt = (
            f"{full_prompt}\n\n"
            f"注意：你上一次的返回无法解析为有效的 JSON 剧本。"
            f"请严格按照 JSON 格式返回，确保包含 shots 数组，每个 shot 有 video_prompt 和 dialogue 字段。"
            f"只返回 JSON，不要有其他文字。"
        )
        result = client.generate_script(repair_prompt, system_prompt=system_prompt)
        if not result:
            raise RuntimeError("修复重试时 LLM 返回为空")
        result = strip_markdown_fence(result)
    
    raise RuntimeError("修复重试后仍无法解析剧本 JSON")


# 单镜时长区间（秒）：H3 原生支持 5-12s，但 >10s 生成时显存溢出，
# 故上限收紧到 10s，推荐 8s 质量最优；系统仅做总时长兜底（每集 ≥75s）
SHOT_DURATION_MIN = 5
SHOT_DURATION_MAX = 10
SHOT_DURATION_DEFAULT = 8
# 每集总时长下限（秒）：9 镜 × 8s = 72s，系统自动把必要镜头逐镜抬高至上限凑够 75s+
EPISODE_MIN_TOTAL_DURATION = 75
# 推荐分镜数（9 镜，节省生成时间）
DEFAULT_SHOT_COUNT = 9


def clamp_shot_duration(value):
    """把单镜时长收敛到 5-10 秒区间；缺失或非法值回退默认 8 秒。"""
    try:
        v = int(round(float(value)))
    except (TypeError, ValueError):
        return SHOT_DURATION_DEFAULT
    if v < SHOT_DURATION_MIN:
        return SHOT_DURATION_MIN
    if v > SHOT_DURATION_MAX:
        return SHOT_DURATION_MAX
    return v


def ensure_min_total_duration(script_data):
    """保证每集分镜总时长 ≥ EPISODE_MIN_TOTAL_DURATION 秒。

    先把每镜收敛到 5-10 秒；若总时长不足则逐镜抬高到上限 10s；
    拉满仍不足（分镜数过少）时抛 RuntimeError。
    Mock 演示剧本不参与总时长治理（仅为无 Key 冒烟测试用）。
    """
    if not isinstance(script_data, dict) or script_data.get("_mock"):
        return script_data
    scenes = script_data.get("shots") or script_data.get("scenes") or []
    shots = [s for s in scenes if isinstance(s, dict)]
    if not shots:
        return script_data
    total = 0.0
    for shot in shots:
        shot["duration_seconds"] = clamp_shot_duration(shot.get("duration_seconds"))
        total += float(shot["duration_seconds"])
    if total >= EPISODE_MIN_TOTAL_DURATION:
        return script_data
    for shot in shots:
        if total >= EPISODE_MIN_TOTAL_DURATION:
            break
        cur = int(shot["duration_seconds"])
        if cur >= SHOT_DURATION_MAX:
            continue
        add = min(SHOT_DURATION_MAX - cur, EPISODE_MIN_TOTAL_DURATION - total)
        shot["duration_seconds"] = cur + add
        total += add
    if total < EPISODE_MIN_TOTAL_DURATION:
        min_shots = -(-EPISODE_MIN_TOTAL_DURATION // SHOT_DURATION_MAX)
        raise RuntimeError(
            f"分镜总时长不足：{len(shots)} 个分镜即使每镜 {SHOT_DURATION_MAX}s "
            f"（合计 {int(total)}s）仍低于每集 {EPISODE_MIN_TOTAL_DURATION}s 下限，"
            f"需至少 {min_shots} 个分镜（建议 {DEFAULT_SHOT_COUNT} 个），请重新生成剧本"
        )
    return script_data


def generate_script_data(prompt, api_config, duration, style, context_data=None, language="zh", 
                         allow_mock=False, panel_count=DEFAULT_SHOT_COUNT, shot_duration=None):
    """
    同步生成剧本数据（dict）。无有效 API Key 且 allow_mock=True 时返回内置演示剧本（mock）。
    生成/解析失败抛出异常，由调用方决定 UI 提示或流水线中断策略。
    
    Args:
        allow_mock: 是否允许 mock 降级（生产环境应为 False）
        panel_count: 目标镜头数
        shot_duration: 每镜头时长（秒）
    """
    api_config = api_config or {}
    api_key = api_config.get("api_key")
    base_url = api_config.get("base_url")
    model = api_config.get("model")

    # Mock 降级：需要显式开启
    if not api_key or api_key == "sk-placeholder":
        if not allow_mock:
            raise RuntimeError("未配置有效的 LLM API Key，且未允许 mock 模式")
        import logging
        logging.getLogger(__name__).warning(
            "[MOCK] LLM API Key 无效，使用内置演示剧本（allow_mock=True）"
        )
        print("=" * 60)
        print("[WARNING] MOCK 模式：正在使用内置演示剧本，非真实 AI 生成！")
        print("=" * 60)
        time.sleep(2)
        mock_data = _dummy_script_data()
        mock_data["_mock"] = True
        return mock_data

    client = LLMClient(api_key=api_key, base_url=base_url, model=model)
    full_prompt = build_script_prompt(prompt, style, duration, context_data, language)

    def _govern(data):
        """时长治理：每镜 5-10 秒收敛 + 全集总时长 ≥75 秒。"""
        scenes = data.get("shots") or data.get("scenes") or []
        for shot in scenes:
            if isinstance(shot, dict):
                if shot_duration:
                    shot["duration_seconds"] = clamp_shot_duration(shot_duration)
                else:
                    shot["duration_seconds"] = clamp_shot_duration(shot.get("duration_seconds"))
        ensure_min_total_duration(data)
        return data

    # 使用带修复重试的解析（专用 system prompt：shots 结构 + 叙事/接戏要求）
    script_data = _govern(parse_with_repair(client, full_prompt, max_retries=1,
                                            system_prompt=SCRIPT_SYSTEM_PROMPT))

    # 剧本语义 QA：占位对白自动修；硬错误（时间倒流/占位对白/空镜）带报告
    # 自动重生成 1 次——本地 LLM 免费，换一次结构正确比人工返工便宜得多。
    try:
        from core.qa.script_qa import (
            check_script, auto_fix_script, format_errors, error_count)
    except ImportError:
        from src.core.qa.script_qa import (
            check_script, auto_fix_script, format_errors, error_count)
    auto_fixed = auto_fix_script(script_data)
    if auto_fixed:
        print("[剧本QA] 已自动剔除占位对白（'无明确对白'等描述性文字，避免被 TTS 朗读）")
    issues = check_script(script_data, panel_count=panel_count)
    n_err = error_count(issues)
    for _iss in issues:
        print(f"[剧本QA] {'错误' if _iss.get('severity') == 'error' else '警告'} "
              f"[{_iss.get('code')}] {_iss.get('message')}")
    if n_err:
        report = format_errors(issues)
        print(f"[剧本QA] 共 {n_err} 个硬错误，带报告自动重生成 1 次。报告内容：\n{report}")
        try:
            retry_prompt = (
                full_prompt
                + "\n\n【上一次生成存在以下问题，本次必须全部修复】\n"
                + report)
            retry_data = parse_with_repair(client, retry_prompt, max_retries=1,
                                           system_prompt=SCRIPT_SYSTEM_PROMPT)
            if isinstance(retry_data, dict):
                retry_data = _govern(retry_data)
                auto_fix_script(retry_data)
                retry_issues = check_script(retry_data, panel_count=panel_count)
                n_retry_err = error_count(retry_issues)
                if n_retry_err <= n_err:
                    print(f"[剧本QA] 重生成完成：硬错误 {n_err} → {n_retry_err}，采用新剧本")
                    script_data = retry_data
                    issues = retry_issues
                else:
                    print(f"[剧本QA] 重生成完成：硬错误 {n_err} → {n_retry_err}（变差），保留原剧本")
        except Exception as qa_e:
            print(f"[剧本QA] 重生成失败（保留原剧本）: {type(qa_e).__name__}: {qa_e}")
    n_final_err = error_count(issues)
    warns = [i for i in issues if i.get("severity") == "warning"]
    _final_shots = script_data.get("shots") or script_data.get("scenes") or []
    print(f"[剧本QA] 最终结果：硬错误 {n_final_err} 个、警告 {len(warns)} 个"
          f"（剧本共 {len(_final_shots)} 镜）")
    for _w in warns:
        print(f"[剧本QA]   警告明细: {_w.get('message')}")

    return script_data


def normalize_script_data(script_data, target_count=None, shot_duration=None):
    """规范化剧本数据：保留所有 shots，补齐缺失字段，可选控制目标数量。
    
    Args:
        target_count: 目标镜头数；None=保留全部，超出保留并告警
        shot_duration: 每镜头时长（秒）；None=保留原值
    """
    scenes = script_data.get("shots", []) or script_data.get("scenes", [])
    shots = list(scenes or [])  # 保留全部，不截断
    
    if target_count is not None and len(shots) > target_count:
        import logging
        logging.getLogger(__name__).warning(
            f"LLM 返回 {len(shots)} 个镜头，超过目标 {target_count}，全部保留"
        )
    
    # 补齐缺失字段（不再虚构空镜）
    for shot in shots:
        if not isinstance(shot, dict):
            continue
        shot.setdefault("shot_id", "")
        shot.setdefault("scene_location", "")
        shot.setdefault("time", "Day")
        shot.setdefault("weather", "Clear")
        shot.setdefault("atmosphere", "")
        shot.setdefault("style", "")
        shot.setdefault("shot_type", "中景")
        shot.setdefault("camera_movement", "固定")
        shot.setdefault("characters", "")
        shot.setdefault("props", "")
        shot.setdefault("action", "")
        shot.setdefault("dialogue", "")
        shot.setdefault("video_prompt", "")
        if shot_duration is not None:
            shot["duration_seconds"] = clamp_shot_duration(shot_duration)
        else:
            shot["duration_seconds"] = clamp_shot_duration(shot.get("duration_seconds"))
    
    if "shots" in script_data:
        script_data["shots"] = shots
    elif "scenes" in script_data:
        script_data["scenes"] = shots
    else:
        script_data["shots"] = shots
    for key in ["characters", "props", "script_scenes"]:
        if key not in script_data:
            script_data[key] = []
    return script_data


def enhance_video_prompts(script_data):
    """为剧本 shots 增强/补齐视频提示词（自 project_window._enhance_video_prompts 迁移）。"""
    script_data = normalize_script_data(script_data)

    # 获取场景列表
    scenes = script_data.get("shots", []) or script_data.get("scenes", [])

    if not scenes:
        return script_data

    for i, scene in enumerate(scenes):
        try:
            # 获取现有视频参数
            video_params = scene.get("video_params", {})

            # 获取对白信息
            dialogue_text = ""
            dialogue_role = ""

            # 处理不同格式的对白
            if "dialogues" in scene and scene["dialogues"]:
                dialogues = scene["dialogues"]
                if isinstance(dialogues, list) and len(dialogues) > 0:
                    first_dlg = dialogues[0]
                    if isinstance(first_dlg, dict):
                        dialogue_text = first_dlg.get("content", "")
                        dialogue_role = first_dlg.get("role", "")
            elif "dialogue" in scene:
                dialogue_text = scene["dialogue"]
                if isinstance(dialogue_text, str) and ':' in dialogue_text:
                    parts = dialogue_text.split(':', 1)
                    dialogue_role = parts[0].strip()
                    dialogue_text = parts[1].strip() if len(parts) > 1 else ''

            # 如果 dialogue 字段为空，尝试从已有 video_prompt 中提取对白
            if not dialogue_text:
                existing_prompt = scene.get("video_prompt", "")
                if existing_prompt:
                    m = re.search(r'- 对白[：:]\s*(.+?)(?:\n|$)', existing_prompt)
                    if m:
                        extracted = m.group(1).strip()
                        if extracted and extracted != '（无）':
                            if '：' in extracted or ':' in extracted:
                                parts = extracted.split('：' if '：' in extracted else ':', 1)
                                dialogue_role = parts[0].strip()
                                dialogue_text = parts[1].strip()
                            else:
                                dialogue_text = extracted

            existing_video_prompt = scene.get("video_prompt", "") or ""
            # 六段式完整格式（含段落标记）→ 保留；简短创意核心 / 空 → 程序化展开成六段式。
            # LLM 现在只输出 1-2 句创意核心（省 3-4 倍 token，避免长输出截断），
            # 【参考图描述】【质量要求】等模板段落由 construct_video_prompt 统一补齐。
            _is_full_format = ("【分镜时间轴】" in existing_video_prompt
                               or "【参考图描述】" in existing_video_prompt
                               or "[Shot Timeline]" in existing_video_prompt
                               or "[Reference Image Description]" in existing_video_prompt)
            # 旧项目的长提示词（LLM 自己写的六段式 + 结构化字段的字典原文）：
            # 长度是紧凑版的 3-4 倍。压缩时**保留创意时间轴**，只砍样板段落，
            # 避免用模板重建导致画面细节变糙（清晰度下降）。
            _is_legacy_bloated = (len(existing_video_prompt) > 2500
                                  or "'name':" in existing_video_prompt
                                  or '"name":' in existing_video_prompt)
            if existing_video_prompt and _is_legacy_bloated:
                try:
                    from core.storyboard.prompt_factory import compact_video_prompt
                except ImportError:
                    from src.core.storyboard.prompt_factory import compact_video_prompt
                _compacted = compact_video_prompt(existing_video_prompt)
                if _compacted and len(_compacted) < len(existing_video_prompt):
                    scene["video_prompt"] = _compacted
                    import logging
                    logging.getLogger(__name__).info(
                        f"Scene {i} video_prompt 压缩: {len(existing_video_prompt)} -> {len(_compacted)} 字符"
                        f"（保留创意时间轴）")
                    continue
            if existing_video_prompt and _is_full_format and not _is_legacy_bloated:
                import logging
                logging.getLogger(__name__).debug(
                    f"Scene {i} already has full-format video_prompt "
                    f"({len(existing_video_prompt)} chars), not overwriting"
                )
            else:
                scene_location = scene.get("scene_location", "")
                atmosphere = scene.get("atmosphere", "")
                style = scene.get("style", "")
                shot_type = scene.get("shot_type", "")
                # 展开时设定 scene_description：
                # LLM 的简短创意核心与场景字段合并（不丢地点）；空 prompt 时纯场景拼接。
                # 调用方已预设 scene_description 时不覆盖，只做创意文本拼接。
                _preset_desc = video_params.get('scene_description') or ""
                if existing_video_prompt and not _is_legacy_bloated:
                    scene_desc = scene.get("description", "") or scene_location or ""
                    if scene_desc and scene_desc != existing_video_prompt:
                        merged = f"{existing_video_prompt}（场景：{scene_desc}）"
                    else:
                        merged = existing_video_prompt
                    if _preset_desc and _preset_desc not in merged:
                        merged = f"{merged}（{_preset_desc}）"
                    video_params['scene_description'] = merged
                elif _preset_desc:
                    # 调用方已给描述，保持不动
                    pass
                else:
                    # 旧的长提示词不再复用（会把它整段塞回时间轴），
                    # 改用场景/分镜描述作为画面主描述
                    scene_desc = scene.get("description", "") or ""
                    if scene_desc:
                        video_params['scene_description'] = scene_desc
                    else:
                        desc_parts = []
                        if scene_location:
                            desc_parts.append(f"场景位于{scene_location}")
                        if atmosphere:
                            desc_parts.append(atmosphere)
                        if style:
                            desc_parts.append(style)
                        video_params['scene_description'] = "，".join(desc_parts) if desc_parts else ""
                if 'characters' not in video_params:
                    video_params['characters'] = scene.get("characters", "")
                if 'action' not in video_params:
                    video_params['action'] = scene.get("action", "")
                if 'props' not in video_params:
                    video_params['props'] = scene.get("props", "")
                if 'atmosphere' not in video_params:
                    video_params['atmosphere'] = atmosphere
                if 'scene_location' not in video_params:
                    video_params['scene_location'] = scene_location
                if 'shot_type' not in video_params:
                    video_params['shot_type'] = shot_type

                # 换场判定：与上一镜 location/time 不同即为换场，
                # 换场镜用"换场建立画面"措辞，避免跨场景强接戏导致画面渐变变形
                _same_scene_prev = True
                if i > 0:
                    _ps = scenes[i - 1]
                    _prev_loc = str(_ps.get("scene_location") or _ps.get("location") or "").strip()
                    _cur_loc = str(scene.get("scene_location") or scene.get("location") or "").strip()
                    _prev_t = str(_ps.get("time") or "").strip()
                    _cur_t = str(scene.get("time") or "").strip()
                    if _prev_loc and _cur_loc:
                        _same_scene_prev = (_prev_loc == _cur_loc and _prev_t == _cur_t)

                enhanced_video_prompt = construct_video_prompt(
                    video_params=video_params,
                    dialogue_text=dialogue_text,
                    dialogue_role=dialogue_role,
                    duration=float(scene.get("duration_seconds", 8)),
                    is_first=(i == 0),
                    is_last=(i == len(scenes) - 1),
                    prev_action=(scenes[i - 1].get("action", "") if i > 0 else ""),
                    same_scene_as_prev=_same_scene_prev
                )

                scene["video_prompt"] = enhanced_video_prompt

        except Exception as e:
            import logging
            logging.getLogger(__name__).warning(
                f"增强 scene {i} 视频提示词失败: {e}", exc_info=True
            )
            continue

    return script_data


def generate_character_prompt(char_data):
    """Generate AI prompt for character with detailed description.

    重点突出性别与国别/族裔，避免绘图模型把中国角色画成欧美面孔、
    或把男性画成女性。性别与国别会在主体段与外貌段各强调一次。
    """
    name = char_data.get("name", "")
    gender = char_data.get("gender", "")
    age = char_data.get("age", "")
    nationality = char_data.get("nationality", "") or char_data.get("ethnicity", "")
    appearance = char_data.get("appearance_features", "")
    style = char_data.get("style_description", "")
    personality = char_data.get("personality", "")
    background = char_data.get("background", "")

    # 性别 → 英文关键词（模型对英文性别词更敏感）
    gender_en = {"男性": "male", "男": "male", "female": "female",
                 "女性": "female", "女": "female"}.get(gender, gender)
    # 国别 → 英文族裔描述
    nat_en = ""
    if nationality:
        if any(k in nationality for k in ("中国", "汉", "华", "China", "Chinese")):
            nat_en = "East Asian (Chinese)"
        elif any(k in nationality for k in ("日本", "Japan", "Japanese")):
            nat_en = "East Asian (Japanese)"
        elif any(k in nationality for k in ("韩国", "Korea", "Korean")):
            nat_en = "East Asian (Korean)"
        elif any(k in nationality for k in ("欧美", "白人", "Caucasian", "White", "Europe", "America")):
            nat_en = "Caucasian"
        elif any(k in nationality for k in ("非洲", "黑人", "African", "Black")):
            nat_en = "African"
        elif any(k in nationality for k in ("印度", "India", "Indian")):
            nat_en = "South Asian (Indian)"
        elif any(k in nationality for k in ("中东", "Arab", "Arabian")):
            nat_en = "Middle Eastern"
        else:
            nat_en = nationality

    identity_parts = []
    if gender:
        identity_parts.append(f"{gender}（{gender_en}）")
    if age:
        identity_parts.append(age)
    if nationality:
        identity_parts.append(f"{nationality}（{nat_en}）")
    identity_line = "，".join(identity_parts) if identity_parts else "未指定"

    prompt = f"[角色/主体]\n"
    prompt += f"角色名称: {name}\n"
    prompt += f"身份: {identity_line}\n"
    # 硬约束：性别与国别必须严格遵循，不可混淆
    if gender:
        prompt += f"性别必须为{gender}（{gender_en}），严禁画成相反性别\n"
    if nationality:
        prompt += f"国别/族裔必须为{nationality}（{nat_en}），面部骨骼、肤色、五官严格符合该族裔特征\n\n"
    else:
        prompt += "\n"

    prompt += f"[外貌特征]\n"
    # 把性别和国别作为外貌的第一要素，确保模型优先处理
    face_parts = []
    if gender:
        face_parts.append(f"{gender_en} face and body")
    if nat_en:
        face_parts.append(f"{nat_en} facial features and skin tone")
    face_parts.append(appearance)
    prompt += f"{', '.join(p for p in face_parts if p)}\n\n"

    if personality:
        prompt += f"[性格特点]\n"
        prompt += f"{personality}\n\n"

    if background:
        prompt += f"[背景信息]\n"
        prompt += f"{background}\n\n"

    prompt += f"[场景环境]\n"
    prompt += f"simple background, neutral studio setting, clean backdrop\n\n"

    prompt += f"[时间天气]\n"
    prompt += f"controlled studio lighting, indoor setting\n\n"

    prompt += f"[光影氛围]\n"
    prompt += f"soft professional lighting, rim light on hair, subtle shadows, portrait lighting setup\n\n"

    prompt += f"[镜头构图]\n"
    prompt += f"medium shot, portrait framing, centered composition, eye-level angle, character focused\n\n"

    prompt += f"[风格画质]\n"
    if style:
        prompt += f"{style}, "
    prompt += f"character portrait, ultra detailed, 8k, masterpiece, best quality, consistent character design, photorealistic, high resolution, sharp focus, professional photography\n\n"

    # 反向提示词里也加上性别/族裔混淆的禁止项
    neg = ("lowres, bad anatomy, bad hands, text, error, missing fingers, extra digit, "
           "fewer digits, cropped, worst quality, low quality, normal quality, jpeg artifacts, "
           "signature, watermark, username, blurry, bad proportions, deformed, disfigured, "
           "extra limbs, missing limbs, floating limbs, disconnected limbs, mutation, mutated, "
           "ugly, disgusting, poorly drawn hands, poorly drawn face, out of frame, extra fingers, "
           "mutated hands, body out of frame, bad art, beginner, amateur, distorted face")
    if gender:
        neg += f", {('female' if gender_en=='male' else 'male')} features, opposite gender"
    if nat_en:
        neg += f", wrong ethnicity, mixed race features"
    prompt += f"[反向提示词]\n{neg}"

    return prompt


