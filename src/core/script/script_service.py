def create_resources_from_data(data, project_dir):
    """Automatically create characters, props, and scenes from generated data.
    返回创建的对象（含已有被跳过的 None 占位），供后续生成资源参考图使用。"""
    created = {
        "characters": [],
        "props": [],
        "scenes": []
    }

    if not project_dir:
        print("DEBUG: No project_dir, skipping resource creation")
        return created

    # Create characters
    characters_data = data.get("characters", [])
    for char_data in characters_data:
        try:
            character = create_character(char_data, project_dir)
            if character:
                created["characters"].append(character)
        except Exception as e:
            print(f"Error creating character {char_data.get('name')}: {e}")

    # Create props
    props_data = data.get("props", [])
    for prop_data in props_data:
        try:
            prop = create_prop(prop_data, project_dir)
            if prop:
                created["props"].append(prop)
        except Exception as e:
            print(f"Error creating prop {prop_data.get('name')}: {e}")

    # Create scenes (handle both "scenes" and "script_scenes" keys)
    scenes_data = data.get("script_scenes", []) or data.get("scenes", [])
    for scene_data in scenes_data:
        try:
            scene = create_scene(scene_data, project_dir)
            if scene:
                created["scenes"].append(scene)
        except Exception as e:
            print(f"Error creating scene {scene_data.get('name')}: {e}")

    return created
