EN_ZH: dict[str, str] = {v: k for k, v in ZH_EN.items() if v != k}
_STATE: list[str] = ["zh-CN"]


def set_language(lang: str) -> None:
    _STATE[0] = "zh-CN" if lang and str(lang).lower().startswith("zh") else "en-US"


def lang() -> str:
    return _STATE[0]


def _lookup(text: str, target: str) -> str:
    if target == "en-US":
        return ZH_EN.get(text, text)
    return EN_ZH.get(text, text)


def t(text: str) -> str:
    return _lookup(text, _STATE[0])


def _translate_text(text: str, target: str) -> str:
    if not text:
        return text
    table = ZH_EN if target == "en-US" else EN_ZH
    if text in table:
        return _lookup(text, target)
    if "\n" in text:
        return "\n".join(_lookup(ln, target) for ln in text.split("\n"))
    return text


def apply_language(root: QWidget, target: str) -> None:
    if target != "en-US":
        target = "zh-CN"
    widgets = [root] + list(root.findChildren(QWidget))
    for w in widgets:
        if isinstance(w, QLabel):
            w.setText(_translate_text(w.text(), target))
        elif isinstance(w, QAbstractButton):
            w.setText(_translate_text(w.text(), target))
        elif isinstance(w, QGroupBox):
            w.setTitle(_translate_text(w.title(), target))
        elif isinstance(w, QLineEdit):
            w.setPlaceholderText(_translate_text(w.placeholderText(), target))
        elif isinstance(w, QPlainTextEdit):
            w.setPlaceholderText(_translate_text(w.placeholderText(), target))
        elif isinstance(w, QComboBox):
            for i in range(w.count()):
                w.setItemText(i, _translate_text(w.itemText(i), target))
        elif isinstance(w, QListWidget):
            for i in range(w.count()):
                w.item(i).setText(_translate_text(w.item(i).text(), target))
        if isinstance(w, QTableWidget) and w.columnCount():
            labels = [
                _translate_text(w.horizontalHeaderItem(c).text(), target)
                if w.horizontalHeaderItem(c) else ""
                for c in range(w.columnCount())
            ]
            w.setHorizontalHeaderLabels(labels)
    if isinstance(root, (QMainWindow, QDialog)):
        root.setWindowTitle(_translate_text(root.windowTitle(), target))
